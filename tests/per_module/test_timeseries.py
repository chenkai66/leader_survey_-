from _common import chk, summary
import numpy as np, calibrate as C
rng = np.random.default_rng(7)
_x = C.ts_ar(3000, ar=(0.7,), rng=rng)
chk("ts_ar lag-1 ≈ 0.7", abs(np.corrcoef(_x[:-1], _x[1:])[0,1] - 0.7) < 0.05)
r, sig = C.ts_garch(5000, omega=0.05, alpha=0.1, beta=0.85, rng=rng)
chk("GARCH volatility clustering", np.corrcoef(r[:-1]**2, r[1:]**2)[0,1] > 0.05)
Y = C.ts_var(2000, A_list=[np.array([[0.5,0.2],[0.1,0.4]])], Sigma=[[1,0.3],[0.3,1]], rng=rng)
chk("VAR shape", Y.shape == (2000, 2))
P_t = np.array([[0.7,0.2,0.1],[0.1,0.8,0.1],[0.2,0.2,0.6]])
seq = C.markov_chain(15000, P_t, states=["A","B","C"], rng=rng)
Ph, _ = C.fit_markov(seq, states=["A","B","C"])
chk("markov P estimate accurate", np.max(np.abs(Ph - P_t)) < 0.02)
states, obs = C.hmm_data(2000, np.array([[0.9,0.1],[0.2,0.8]]),
                          emission_means=[0,3], emission_sds=[1,1], rng=rng)
chk("HMM state-conditional mean differs", abs(obs[states==1].mean() - obs[states==0].mean()) > 2)
events = C.hawkes_process(50, mu=1.0, alpha=0.4, beta=1.0, rng=rng)
chk("Hawkes more events than baseline", len(events) > 50)
chk("count NB overdispersed", C.count_data(5000, 3.0, dispersion=1.0, rng=rng).var() > 2 * 3.0)
y, lab = C.ts_anomaly_inject(C.ts_ar(500, ar=(0.5,), rng=rng), point_rate=0.02, level_shift=[(200, 3.0)], rng=rng)
chk("ts_anomaly level shift visible", abs(y[250:300].mean() - y[100:150].mean()) > 1.5)
ycp, seg = C.change_point_series(500, [100, 300], [0, 3, -1], noise_sd=0.5, rng=rng)
chk("change_point segment means correct", abs(ycp[seg==1].mean() - 3) < 0.2)
summary()
